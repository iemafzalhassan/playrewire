// Generates src/design/tokens.css from design/tokens.json (the single source).
// Runs before dev, build and test (package.json pre-scripts). Node strips the
// types, so no build step is needed: `node scripts/tokens.ts`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type Tokens = Record<string, unknown>;

/** Flatten {color:{paper:"#.."}} into ["--paper", "#.."]; colors drop the group prefix. */
function flatten(tokens: Tokens): [string, string][] {
  const out: [string, string][] = [];
  for (const [group, value] of Object.entries(tokens)) {
    if (group.startsWith("$") || typeof value !== "object" || value === null) continue;
    for (const [name, v] of Object.entries(value as Record<string, unknown>)) {
      if (typeof v !== "string") throw new Error(`token ${group}.${name} must be a string`);
      const prop = group === "color" ? `--${name}` : `--${group}-${name}`;
      out.push([prop, v]);
    }
  }
  return out;
}

export function renderTokensCss(tokens: Tokens): string {
  const lines = flatten(tokens).map(([k, v]) => `  ${k}: ${v};`);
  return [
    "/* Generated by apps/web/scripts/tokens.ts from design/tokens.json. Do not edit. */",
    ":root {",
    ...lines,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = new URL("../../../design/tokens.json", import.meta.url);
  const dest = new URL("../src/design/tokens.css", import.meta.url);
  const css = renderTokensCss(JSON.parse(readFileSync(src, "utf8")));
  let old = "";
  try {
    old = readFileSync(dest, "utf8");
  } catch {}
  if (old !== css) {
    writeFileSync(dest, css);
    console.log(`tokens: wrote ${fileURLToPath(dest)}`);
  }
}
