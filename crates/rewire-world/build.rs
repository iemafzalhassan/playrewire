//! Reads `design/tokens.json` (the single source of design tokens) into `tokens.rs`, so
//! the street is drawn in exactly the app's paper, ink and accent.

use std::{env, fs, path::Path};

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let path = Path::new(&manifest).join("../../design/tokens.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).expect("read design/tokens.json");
    let json: serde_json::Value = serde_json::from_str(&text).expect("tokens.json is JSON");

    let mut out = String::from("// Generated by build.rs from design/tokens.json. Do not edit.\n\n");
    let colors = json["color"].as_object().expect("tokens.json has a color table");
    for (name, value) in colors {
        let hex = value.as_str().expect("colour tokens are strings");
        let rgb = parse_hex(hex).unwrap_or_else(|| panic!("colour {name} is not #rrggbb: {hex}"));
        let ident = name.replace('-', "_").to_uppercase();
        out += &format!(
            "/// `{hex}` (`color.{name}`)\npub const {ident}: [u8; 3] = [{}, {}, {}];\n",
            rgb[0], rgb[1], rgb[2]
        );
    }
    let ms = |key: &str| -> u32 {
        json["motion"][key]
            .as_str()
            .and_then(|s| s.strip_suffix("ms"))
            .and_then(|s| s.parse().ok())
            .unwrap_or_else(|| panic!("motion.{key} is not a ms value"))
    };
    out += &format!(
        "/// `motion.boil-step`: how long one hand-drawn line pose holds, in seconds.\npub const BOIL_STEP: f32 = {:.3};\n",
        ms("boil-step") as f32 / 1000.0
    );
    out += &format!(
        "/// `motion.slow` in seconds.\npub const SLOW: f32 = {:.3};\n",
        ms("slow") as f32 / 1000.0
    );

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("tokens.rs");
    fs::write(dest, out).expect("write tokens.rs");
}

fn parse_hex(s: &str) -> Option<[u8; 3]> {
    let s = s.strip_prefix('#')?;
    if s.len() != 6 {
        return None;
    }
    let n = u32::from_str_radix(s, 16).ok()?;
    Some([(n >> 16) as u8, (n >> 8) as u8, n as u8])
}
